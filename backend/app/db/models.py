"""Persistence models. Business rules live in app.domain; API schemas live in app.domain.schemas.

Conventions (see docs/PHASE2_FOUNDATION.md):
- Primary keys are UUIDs, generated by the application and by the database default.
- Timestamps are timestamptz in UTC, set by the database.
- Every organization-owned row carries organization_id; access is always checked through a membership.
"""

import uuid
from datetime import datetime

from sqlalchemy import CheckConstraint, DateTime, ForeignKey, Index, String, UniqueConstraint, Uuid, func, text
from sqlalchemy.orm import Mapped, mapped_column

from app.db.base import Base
from app.domain.access import ROLE_VALUES

ORGANIZATION_STATUS_VALUES = ("active", "suspended")
SLUG_PATTERN = "^[a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?$"


def _uuid_pk() -> Mapped[uuid.UUID]:
    return mapped_column(Uuid(as_uuid=True), primary_key=True, default=uuid.uuid4, server_default=text("gen_random_uuid()"))


def _created_at() -> Mapped[datetime]:
    return mapped_column(DateTime(timezone=True), nullable=False, server_default=func.now())


class Organization(Base):
    """A client account of RCKT. RCKT's own staff also belong to an internal organization."""

    __tablename__ = "organizations"
    __table_args__ = (
        UniqueConstraint("slug", name="uq_organizations_slug"),
        CheckConstraint(f"slug ~ '{SLUG_PATTERN}'", name="slug_format"),
        CheckConstraint(
            "status IN (" + ", ".join(f"'{v}'" for v in ORGANIZATION_STATUS_VALUES) + ")",
            name="status_valid",
        ),
    )

    id: Mapped[uuid.UUID] = _uuid_pk()
    name: Mapped[str] = mapped_column(String(120), nullable=False)
    slug: Mapped[str] = mapped_column(String(63), nullable=False)
    status: Mapped[str] = mapped_column(String(16), nullable=False, server_default="active")
    created_at: Mapped[datetime] = _created_at()
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, server_default=func.now(), onupdate=func.now()
    )


class AppUser(Base):
    """Local record of a person authenticated by the managed identity provider.

    Passwords are never stored here. external_subject is the stable identifier issued by the provider.
    """

    __tablename__ = "app_users"
    __table_args__ = (UniqueConstraint("external_subject", name="uq_app_users_external_subject"),)

    id: Mapped[uuid.UUID] = _uuid_pk()
    external_subject: Mapped[str] = mapped_column(String(255), nullable=False)
    email: Mapped[str | None] = mapped_column(String(320), nullable=True)
    created_at: Mapped[datetime] = _created_at()


class OrganizationMembership(Base):
    """Links a user to an organization with exactly one role in it."""

    __tablename__ = "organization_memberships"
    __table_args__ = (
        UniqueConstraint("organization_id", "user_id", name="uq_organization_memberships_org_user"),
        CheckConstraint("role IN (" + ", ".join(f"'{v}'" for v in ROLE_VALUES) + ")", name="role_valid"),
        Index("ix_organization_memberships_user_id", "user_id"),
    )

    id: Mapped[uuid.UUID] = _uuid_pk()
    organization_id: Mapped[uuid.UUID] = mapped_column(
        Uuid(as_uuid=True),
        ForeignKey("organizations.id", ondelete="RESTRICT", name="fk_organization_memberships_organization_id"),
        nullable=False,
    )
    user_id: Mapped[uuid.UUID] = mapped_column(
        Uuid(as_uuid=True),
        ForeignKey("app_users.id", ondelete="RESTRICT", name="fk_organization_memberships_user_id"),
        nullable=False,
    )
    role: Mapped[str] = mapped_column(String(32), nullable=False)
    created_at: Mapped[datetime] = _created_at()
